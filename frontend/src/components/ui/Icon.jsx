/**
 * @param {object} props
 * @param {string} props.name    Key from the registry above.
 * @param {number} [props.size]  Rendered px size (width and height).
 * @param {number} [props.strokeWidth]
 * @param {string} [props.title] When present the icon is exposed to assistive
 *                               tech with this label; otherwise it is hidden,
 *                               which is correct for icons beside text.
 */
export default function Icon({
    name,
    size = 16,
    strokeWidth = 2,
    title,
    className,
    ...rest
}) {
    const filled = FILLED[name];
    const glyph = filled ?? STROKE[name];

    if (!glyph) {
        if (import.meta.env.DEV) console.warn(`Icon "${name}" is not registered`);
        return null;
    }

    return (
        <svg
            xmlns="http://www.w3.org/2000/svg"
            width={size}
            height={size}
            viewBox="0 0 24 24"
            fill={filled ? 'currentColor' : 'none'}
            stroke={filled ? 'none' : 'currentColor'}
            strokeWidth={filled ? undefined : strokeWidth}
            strokeLinecap="round"
            strokeLinejoin="round"
            className={className}
            role={title ? 'img' : undefined}
            aria-label={title || undefined}
            aria-hidden={title ? undefined : 'true'}
            focusable="false"
            {...rest}
        >
            {title ? <title>{title}</title> : null}
            {glyph}
        </svg>
    );
}
